"""
Generate contract/types.ts from contract/models.py.

    python contract/gen_types.py

Rules
- Response shapes: every field is present in JSON (Pydantic dumps defaults),
  so fields are required in TS and nullable where the Python type is Optional.
- Request shapes (REQUEST_MODELS): fields with a default are optional (?).
- Named Literal aliases (RunStatus, Stage, ...) and the discriminated unions
  (Event, Item, Block, Locator) are exported by name.
Never edit types.ts by hand.
"""
from __future__ import annotations

import inspect
import json
import types
import typing
from pathlib import Path

from pydantic import BaseModel
from pydantic_core import PydanticUndefined

HERE = Path(__file__).resolve().parent
import sys  # noqa: E402

sys.path.insert(0, str(HERE))
import models as m  # noqa: E402

REQUEST_MODELS = {"CreateRunRequest", "StopRequest", "AddSourceRequest", "SourceDecision", "ApprovalRequest", "RevokeRequest",
                  "ItemPatch", "CommentRequest", "InjectErrorsRequest"}
UNION_ALIASES = {"Event": m.Event, "Item": m.Item, "Block": m.Block, "Locator": m.Locator}


def literal_aliases() -> dict[int, str]:
    out = {}
    for name, val in vars(m).items():
        if typing.get_origin(val) is typing.Literal and not name.startswith("_"):
            out[id(val)] = name
    return out


LIT = literal_aliases()


def union_id(tp) -> int | None:
    for name, alias in UNION_ALIASES.items():
        if tp is alias or (typing.get_origin(tp) is typing.Annotated and typing.get_args(tp)[0] == typing.get_args(alias)[0]):
            return name
    return None


def ts(tp) -> str:
    if tp is type(None):
        return "null"
    if id(tp) in LIT:
        return LIT[id(tp)]
    name = union_id(tp)
    if name:
        return name
    origin = typing.get_origin(tp)
    if origin is typing.Annotated:
        return ts(typing.get_args(tp)[0])
    if origin is typing.Literal:
        return " | ".join(json.dumps(a) for a in typing.get_args(tp))
    if origin in (typing.Union, types.UnionType):
        parts = [ts(a) for a in typing.get_args(tp)]
        return " | ".join(dict.fromkeys(parts))
    if origin in (list, typing.List):
        inner = ts(typing.get_args(tp)[0])
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if origin in (dict, typing.Dict) or tp is dict:
        return "Record<string, unknown>"
    if isinstance(tp, typing.ForwardRef):
        return tp.__forward_arg__
    if isinstance(tp, str):
        return tp
    if inspect.isclass(tp) and issubclass(tp, BaseModel):
        return tp.__name__
    return {str: "string", int: "number", float: "number", bool: "boolean"}.get(tp, "unknown")


def main() -> None:
    lines = [
        "// GENERATED by contract/gen_types.py from contract/models.py. Do not edit by hand.",
        f"// Contract version {(HERE / 'VERSION').read_text().strip()}",
        "",
    ]
    for name, val in vars(m).items():
        if id(val) in LIT and LIT[id(val)] == name:
            lines.append(f"export type {name} = {' | '.join(json.dumps(a) for a in typing.get_args(val))};")
    lines.append("")
    classes = [c for _, c in inspect.getmembers(m, inspect.isclass)
               if issubclass(c, BaseModel) and c.__module__ == m.__name__ and c.__name__ not in ("Model", "_EventBase")]
    classes.sort(key=lambda c: inspect.getsourcelines(c)[1])
    for c in classes:
        doc = (c.__doc__ or "").strip().splitlines()
        if doc and c.__doc__ != BaseModel.__doc__:
            lines.append(f"/** {doc[0]} */")
        lines.append(f"export interface {c.__name__} {{")
        for fname, f in c.model_fields.items():
            optional = c.__name__ in REQUEST_MODELS and (f.default is not PydanticUndefined or f.default_factory is not None)
            lines.append(f"  {fname}{'?' if optional else ''}: {ts(f.annotation)};")
        lines.append("}")
        lines.append("")
    for name, alias in UNION_ALIASES.items():
        members = typing.get_args(typing.get_args(alias)[0])
        lines.append(f"export type {name} = {' | '.join(x.__name__ for x in members)};")
    lines.append("")
    lines.append(f"export const EVENT_TYPES = {json.dumps(m.EVENT_TYPES)} as const;")
    lines.append("export type EventType = Event[\"type\"];")
    lines.append("/** Narrow an event by its type: `isEvent(e, \"gateway.request\")` gives `e.data` its exact shape. */")
    lines.append("export function isEvent<T extends EventType>(e: Event, type: T): e is Extract<Event, { type: T }> {")
    lines.append("  return e.type === type;")
    lines.append("}")
    (HERE / "types.ts").write_text("\n".join(lines) + "\n")
    print(f"wrote contract/types.ts: {len(classes)} interfaces, {len([v for v in LIT.values()])} enums")


if __name__ == "__main__":
    main()
